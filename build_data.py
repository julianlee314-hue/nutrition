# Regenerates data/index.json manifest and data.js (file:// fallback) from data/*.json
import json,glob,os
os.chdir(os.path.dirname(os.path.abspath(__file__)))
days=sorted(os.path.basename(p)[:-5] for p in glob.glob('data/days/*.json'))
json.dump({"days":days,"pantry":"data/pantry.json","training":"data/training.json","extras":"data/extras.json"},open('data/index.json','w'),indent=2)
b={"index":{"days":days},"days":{d:json.load(open(f'data/days/{d}.json')) for d in days},
 "pantry":json.load(open('data/pantry.json')),"training":json.load(open('data/training.json')),"extras":json.load(open('data/extras.json'))}
open('data.js','w').write('// generated by build_data.py, do not edit\nwindow.NUTRITION_DATA='+json.dumps(b,indent=1)+';\n')
print('days:',days)
